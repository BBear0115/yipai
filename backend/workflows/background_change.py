"""Scene descriptions for editing the source image's background only."""


SCENES = {
    'white': '纯白色无缝摄影棚背景，明亮干净的电商白底，柔和自然落影',
    'studio_gray': '浅灰色无缝摄影棚背景，柔和棚拍光，低对比度商业摄影',
    'outdoor_street': '浪漫城市街道背景，石材铺地、街边建筑、柔和自然光和轻微景深',
    'indoor_minimal': '明亮简约的室内空间，白墙、自然窗光和克制的生活方式氛围',
    'beach': '开阔海边与礁石海岸，细沙、清爽自然天光和真实度假氛围',
    'cafe': '有格调的咖啡馆，暖木、米色墙面、庭院绿植、柔和窗光和安静的生活方式氛围',
}


def build_background_change_prompt(scene_type: str) -> str:
    """Describe a scene replacement while protecting the source subject."""
    if scene_type not in SCENES:
        raise ValueError(f'Unsupported scene_type: {scene_type}. Must be one of {list(SCENES)}')
    scene_desc = SCENES[scene_type]

    return f"""【只换背景硬规则】
这是一次原图背景编辑。唯一输入图（图1）是待编辑原图，也是主体、商品和构图的唯一来源。
只移除图1原背景，替换为以下场景：{scene_desc}。

主体锁定：图1有人物才保留人物；如果图1是平铺、挂拍或无人商品图，只保留原商品及其摆放、悬挂方式，不得添加人物、脸、手、身体或人台，不得把商品自动穿到模特身上。
人物锁定：图1有人物时，保留图1同一张脸、发型、肤色、身体比例、表情、视线、姿势、手部和身体位置，不换人、不增减人物。
服装保真：严格保留图1服装的品类、版型、固有色、图案、文字/logo、纽扣、口袋、拉链、面料纹理、穿搭层次与配饰；不得改款、换色或套风格滤镜。
画幅锁定：保持图1原始画幅比例、拍摄角度、镜头距离、主体大小、主体在画面中的位置和可见范围。不得裁掉服装或补出裁切外的人体。
场景适配：新背景必须适应原主体的拍摄角度。平铺商品仍按同一俯拍角度展示在场景对应的平面上（例如咖啡馆暖木桌面、海边沙面）；挂拍商品保留挂拍展示。不要为了迁就场景改变商品的摆放方式。
真实融合：按场景匹配环境光、色温、透视和景深，保留自然接触阴影；不得改变服装固有色和面料质感。避免白边、硬切边、漂浮感和贴纸感。
输出一张写实商业摄影图片，原主体清晰，背景克制。不要添加原图没有的人物、衣物、包、配饰、文字、边框或水印。"""
